def class_name(command: str) -> str:
    return command[0].upper() + command[1:] + "Cmd"


def _simple(fqcn: str) -> str:
    """The class name a Java source file refers to, given an import."""
    return fqcn.rsplit(".", 1)[-1]


def render_params(params: tuple[Param, ...]) -> str:
    out = []
    for param in params:
        entity = (
            f",\n            entityType = {_simple(param.entity)}.class"
            if param.entity else ""
        )
        required = ", required = true" if param.required else ""
        # @Parameter caps a STRING at 255 unless told otherwise, which
        # no PEM or other blob can meet.
        length = f", length = {param.length}" if param.length else ""
        java_type = {
            "STRING": "String", "INTEGER": "Integer", "LONG": "Long",
            "BOOLEAN": "Boolean", "UUID": "Long",
        }[param.type]
        out.append(
            f'    @Parameter(name = "{param.name}", type = CommandType.{param.type}{entity}'
            f"{required}{length},\n"
            f'            description = "{param.doc}")\n'
            f"    private {java_type} {param.java};"
        )
    return "\n\n".join(out)


def render_path(command: Command) -> str:
    path = command.path
    expr = '"' + path + '"'
    for param in command.params:
        placeholder = "{" + param.java + "}"
        if placeholder in path:
            expr = expr.replace(placeholder, '" + ' + param.java + ' + "')
    expr = expr.replace(' + ""', "").replace('"" + ', "")
    body = f"        String path = {expr};"
    for java in command.query:
        body += f'\n        path = withQuery(path, "{_wire_for(command, java)}", {java});'
    body += "\n        return path;"
    return body


def _wire_for(command: Command, java: str) -> str:
    for param in command.params:
        if param.java == java:
            return param.wire or param.name
    return java


def _body_lines(param: Param) -> str:
    """One parameter's contribution to the request body.

    A `resolve` parameter arrives as the internal id CloudStack
    translated the UUID into, and the engine stores what it is sent and
    compares it against the UUIDs CloudStack returns from its own list
    calls. Sending the number would record an id matching nothing, so
    it is translated back here.
    """
    if param.is_list:
        # CloudStack hands a list parameter over as a comma-separated
        # string; the engine's model wants an array.
        return (
            f"        if ({param.java} != null) {{\n"
            f"            JsonArray values{param.java[0].upper()}{param.java[1:]} ="
            f" new JsonArray();\n"
            f'            for (String part : {param.java}.split(",")) {{\n'
            f"                String trimmed = part.trim();\n"
            f"                if (!trimmed.isEmpty()) {{\n"
            f"                    values{param.java[0].upper()}{param.java[1:]}"
            f".add(trimmed);\n"
            f"                }}\n"
            f"            }}\n"
            f'            body.add("{wire_name(param)}",'
            f" values{param.java[0].upper()}{param.java[1:]});\n"
            f"        }}"
        )

    if not param.resolve:
        return (
            f"        if ({param.java} != null) {{\n"
            f'            body.addProperty("{wire_name(param)}", {param.java});\n'
            f"        }}"
        )

    cls = _simple(param.resolve)
    local = "resolved" + cls
    return (
        f"        if ({param.java} != null) {{\n"
        f"            {cls} {local} = _entityMgr.findById({cls}.class, {param.java});\n"
        f"            if ({local} == null) {{\n"
        f"                throw new InvalidParameterValueException(\n"
        f'                        "Unable to find a {cls.lower()} with the given id");\n'
        f"            }}\n"
        f'            body.addProperty("{wire_name(param)}", {local}.getUuid());\n'
        f"        }}"
    )


def snake(name: str) -> str:
    """The engine's spelling of a Java field name."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def wire_name(param: Param) -> str:
    """The JSON field this parameter travels as."""
    return param.wire or snake(param.java)


def render_body(command: Command) -> str:
    body_params = [param for param in command.params
                   if "{" + param.java + "}" not in command.path and
                   param.java not in command.query]
    if not body_params:
        return ""
    lines = "\n".join(_body_lines(param) for param in body_params)
    return f"""
    @Override
    protected String engineBody() {{
        JsonObject body = new JsonObject();
{lines}
        return body.toString();
    }}
"""


def render_command(command: Command) -> str:
    cls = class_name(command.name)
    imports = [
        "org.apache.cloudstack.acl.RoleType",
        "org.apache.cloudstack.api.APICommand",
        "org.apache.cloudstack.api.Parameter",
    ]
    if command.success_response:
        imports.append("org.apache.cloudstack.api.response.SuccessResponse")
        response_type = "SuccessResponse"
    else:
        imports.append(
            f"org.apache.cloudstack.ai.api.response.{command.response}")
        response_type = command.response

    has_body = bool(render_body(command))
    if has_body:
        imports.append("com.google.gson.JsonObject")
        if any(param.is_list for param in command.params):
            imports.append("com.google.gson.JsonArray")

    # An entityType or a resolution names a class the file must import.
    # Emitting the reference without the import is how setting `entity`
    # used to produce Java that did not compile.
    for param in command.params:
        if param.entity:
            imports.append(param.entity)
        if param.resolve:
            imports.append(param.resolve)
            imports.append("com.cloud.exception.InvalidParameterValueException")
    if command.event:
        imports.append("org.apache.cloudstack.ai.AiServicesEvents")
    if command.is_async:
        imports.append("org.apache.cloudstack.ai.engine.EngineJob")
    else:
        # Both list and plain sync commands take a JsonObject: one per
        # item, one for the whole body.
        imports.append("com.google.gson.JsonObject")

    import_block = "\n".join(
        f"import {i};" for i in sorted(set(imports)) if not i.startswith("com.google"))
    gson_block = "\n".join(
        f"import {i};" for i in sorted(set(imports)) if i.startswith("com.google"))
    if gson_block:
        import_block += "\n\n" + gson_block

    naming = f'    public static final String APINAME = "{command.name}";'
    params = render_params(command.params)
    path_method = (
        "    @Override\n    protected String enginePath() {\n"
        + render_path(command) + "\n    }"
    )
    method_override = (
        f'\n    @Override\n    protected String engineMethod() {{\n'
        f'        return "{command.method}";\n    }}\n'
        if command.method != ("POST" if command.is_async else "GET") else ""
    )

    if command.is_async:
        extends = "AiServicesAsyncCmd"
        success = (
            "    @Override\n    protected void onSuccess(EngineJob job) {\n"
            f"        {response_type} response = {response_type}.from(job.getResult());\n"
            "        response.setResponseName(getCommandName());\n"
            "        setResponseObject(response);\n    }\n\n"
            "    @Override\n    public String getEventType() {\n"
            f"        return AiServicesEvents.{command.event};\n    }}\n\n"
            "    @Override\n    public String getEventDescription() {\n"
            f'        return "{command.event_doing} " + {_subject(command)};\n    }}'
        )
    elif command.items_key:
        extends = f"AiServicesListCmd<{response_type}>"
        success = (
            "    @Override\n    protected String itemsKey() {\n"
            f'        return "{command.items_key}";\n    }}\n\n'
            "    @Override\n"
            f"    protected {response_type} mapItem(JsonObject item) {{\n"
            f"        return {response_type}.from(item);\n    }}"
        )
    else:
        extends = "AiServicesSyncCmd"
        if command.success_response:
            success = (
                "    @Override\n    protected void onSuccess(JsonObject body) {\n"
                "        SuccessResponse response = new SuccessResponse(getCommandName());\n"
                "        response.setSuccess(true);\n"
                "        setResponseObject(response);\n    }"
            )
        else:
            success = (
                "    @Override\n    protected void onSuccess(JsonObject body) {\n"
                f"        {response_type} response = {response_type}.from(body);\n"
                "        response.setResponseName(getCommandName());\n"
                "        setResponseObject(response);\n    }"
            )

    sections = [naming]
    if params:
        sections.append(params)
    sections.append(path_method + method_override)
    body = render_body(command)
    if body:
        sections.append(body.strip())
    sections.append(success)

    return f"""{LICENCE}{GENERATED}package org.apache.cloudstack.ai.api.command;

{import_block}

/** {command.doc} (SPEC.md section 9). */
@APICommand(name = {cls}.APINAME,
        description = "{command.doc}",
        responseObject = {response_type}.class,
        requestHasSensitiveInfo = false,
        responseHasSensitiveInfo = {str(command.name == "createAiApiKey").lower()},
        authorized = {{{authorized_roles(command.name)}}})
public class {cls} extends {extends} {{

{chr(10).join(s + chr(10) for s in sections).rstrip()}
}}
"""


def authorized_roles(name: str) -> str:
    """The RoleTypes that may call this command, for `@APICommand`.

    CloudStack's `DynamicRoleBasedAPIAccessChecker.start()` reads this
    annotation off every `PluggableService`'s commands and consults it
    whenever no explicit `role_permissions` rule matches the caller's
    role. Without it a plugin's commands reach root admin alone, which
    is how a live management server denied a tenant all thirty-eight.

    An explicit rule still wins either way: the checker returns on the
    first matching rule, so the restricted default roles — which end
    in `*  DENY` — never reach this fallback, and an operator can deny
    or grant any of these by hand.

    `ResourceAdmin` is deliberately never emitted. The engine models
    three roles, and inventing a grant for a fourth is worse than
    leaving it to an operator who wants one.
    """
    command = next((c for c in ENGINE_COMMANDS if c.name == name), None)
    if command is None:
        raise SystemExit(f"{name} is not in aisvc/api/commands.py")
    order = ["Admin", "DomainAdmin", "User"]
    names = sorted({role.value for role in command.roles}, key=order.index)
    return ", ".join(f"RoleType.{n}" for n in names)


def _subject(command: Command) -> str:
    for param in command.params:
        if param.required:
            return param.java
    return '"the platform"'


SAMPLE_VALUES = {
    "String": "sample",
    "Integer": 7,
    "Long": 1234,
    "Boolean": True,
    "Double": 1.5,
}


def render_fixture() -> str:
    """A fully-populated engine object per response type.

    Emitted as a test resource so the Java round-trip test exercises
    every mapped field without that list being maintained twice.
    """
    import json

    fixture = {
        response.name: {
            fl.wire: SAMPLE_VALUES[fl.type] for fl in response.fields
        }
        for response in RESPONSES
    }
    return json.dumps(fixture, indent=2, sort_keys=True) + "\n"


def main() -> int:
    written = []
    for response in RESPONSES:
        target = PKG / "response" / f"{response.name}.java"
        target.write_text(render_response(response), encoding="utf-8")
        written.append(target)
    for command in COMMANDS:
        target = PKG / "command" / f"{class_name(command.name)}.java"
        target.write_text(render_command(command), encoding="utf-8")
        written.append(target)

    fixture = ROOT / "src/test/resources/generated-engine-objects.json"
    fixture.parent.mkdir(parents=True, exist_ok=True)
    fixture.write_text(render_fixture(), encoding="utf-8")
    written.append(fixture)

    print(f"generated {len(written)} files")
    registration = "\n".join(
        f"        commands.add({class_name(c.name)}.class);"
        for c in COMMANDS
        if c.release == "v1"
    )
    registration += "\n\n// v2, registered only when ai.services.v2.enabled:\n"
    registration += "\n".join(
        f"        commands.add({class_name(c.name)}.class);"
        for c in COMMANDS
        if c.release == "v2"
    )
    (ROOT / "target" / "generated-registration.txt").parent.mkdir(
        parents=True, exist_ok=True)
    (ROOT / "target" / "generated-registration.txt").write_text(
        registration, encoding="utf-8")
    print("registration snippet written to target/generated-registration.txt")
    return 0


if __name__ == "__main__":
    sys.exit(main())
