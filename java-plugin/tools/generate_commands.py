@dataclass(frozen=True)
class Param:
    name: str          # API parameter name
    java: str          # Java field
    type: str          # STRING | INTEGER | LONG | BOOLEAN | UUID
    doc: str
    required: bool = False
    #: Fully-qualified response class for `entityType`. Giving one makes
    #: CloudStack check the caller may see the entity before the command
    #: runs, and hand back its **internal numeric id** rather than the
    #: UUID that was sent.
    entity: str | None = None
    #: Fully-qualified entity interface to translate that id back
    #: through, for a body the engine can match against CloudStack's own
    #: UUIDs. Without it an `entity` param would send a bare number.
    resolve: str | None = None
    #: The engine's JSON field name, where it differs from the Java
    #: one. Leave it unset and the body carries the snake_case of the
    #: Java name, which is what the engine's models use.
    #:
    #: It used to mean "this parameter belongs in the body at all",
    #: and was therefore set only where the two names differed —
    #: `baseModel` to `base_model`, `customDomain` to `custom_domain`.
    #: Every parameter whose name already matched was left without
    #: one and silently never sent, so seven v2 write commands posted
    #: a body missing exactly the fields that needed no translation.
    #: Whether a parameter is in the body is decided by the path and
    #: the query list, not here.
    wire: str | None = None
    #: `@Parameter`'s own `length()`, which defaults to 255 — a cap no
    #: PEM, JSONL or other blob can meet. CloudStack's
    #: `UploadCustomCertificateCmd` sets 65535 for the same reason.
    length: int | None = None
    #: True where the engine's model declares `list[str]`. CloudStack
    #: takes the value as a comma-separated string either way; without
    #: this the body carried a string into a field typed as a list and
    #: the engine answered 422.
    is_list: bool = False


@dataclass(frozen=True)
class Command:
    name: str
    doc: str
    path: str                      # may contain {java-field} placeholders
    method: str = "GET"
    is_async: bool = False
    response: str = ""
    items_key: str | None = None   # set for list commands
    event: str | None = None
    event_doing: str = ""
    params: tuple[Param, ...] = ()
    query: tuple[str, ...] = ()    # java fields appended as query parameters
    success_response: bool = False
    #: "v1" ships in GA; "v2" is generated but registered only when
    #: ai.services.v2.enabled is on, so the release boundary in
    #: aisvc/api/commands.py holds on this side too.
    release: str = "v1"


def p(name, java, type_, doc, required=False, entity=None, wire=None,
      resolve=None, length=None, is_list=False) -> Param:
    return Param(name, java, type_, doc, required, entity, resolve, wire, length, is_list)


